function pickByDay<T extends { level?: PracticeLevel }>(
  list: T[],
  salt: number,
  dateKey: string,
  level?: PracticeLevel
): T {
  const day = dayNumberFromKey(dateKey);
  const filtered = level ? list.filter((item) => item.level === level) : list;
  const pool = filtered.length > 0 ? filtered : list;
  return pool[(day + salt) % pool.length]!;
}

/** Sugerencias del día (una por habilidad), deterministas por fecha y adaptadas al nivel del jugador. */
export function getDailyPractice(dateKey: string = localDateKey(), level?: PracticeLevel) {
  return {
    speaking: pickByDay(SPEAKING_TOPICS, 3, dateKey, level),
    listening: pickByDay(LISTENING_TRACKS, 1, dateKey, level),
    reading: pickByDay(READING_PASSAGES, 2, dateKey, level),
    writing: pickByDay(WRITING_PROMPTS, 5, dateKey, level),
  };
}

